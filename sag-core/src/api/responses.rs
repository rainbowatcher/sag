/// `POST /v1/responses` request body.
///
/// Every field is optional on the wire: `model` and `input` are only required
/// by the upstream API, and the gateway validates them semantically.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ResponsesRequest {
    #[serde(skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    /// A plain text string or an array of [`InputItem`]s.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub input: Option<ResponsesInput>,
    /// System/developer prompt. Not inherited across `previous_response_id`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instructions: Option<MessageContent>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<ResponsesTool>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<ToolChoiceParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub text: Option<ResponseTextParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reasoning: Option<ReasoningParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub temperature: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub top_p: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub top_logprobs: Option<u8>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_output_tokens: Option<u64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_tool_calls: Option<u32>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stream: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stream_options: Option<StreamOptions>,
    /// Kept as raw JSON on purpose: the ingress layer rejects the string form
    /// `"true"` (and `background`) with a specific 422 *before* typed parsing,
    /// and `store: "false"` must still pass through untouched.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub store: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub metadata: Option<Map<String, Value>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub previous_response_id: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub conversation: Option<ConversationParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parallel_tool_calls: Option<bool>,
    /// `auto` | `default` | `flex` | `scale` | `priority` | `fast` | `ultrafast`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub service_tier: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub prompt: Option<PromptParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub prompt_cache_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub prompt_cache_options: Option<PromptCacheOptionsParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub safety_identifier: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub context_management: Option<Vec<ContextManagementParam>>,
    /// e.g. `message.output_text.logprobs`, `reasoning.encrypted_content`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub include: Option<Vec<String>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub moderation: Option<ModerationParam>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub access_programs: Option<AccessProgramsParam>,
    /// Raw for the same reason as [`Self::store`].
    #[serde(skip_serializing_if = "Option::is_none")]
    pub background: Option<Value>,
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

