//! Typed serde DTOs for the OpenAI Responses API (`POST /v1/responses`).
//!
//! Coverage follows the official Responses OpenAPI schema:
//!
//! * [`ResponsesRequest`] — request body (`CreateResponse`).
//! * [`ResponsesResponse`] — the `response` object returned to clients.
//! * [`InputItem`] / [`OutputItem`] — the polymorphic `input` / `output` arrays.
//! * [`ResponsesTool`] — every tool kind accepted in `tools`.
//! * [`ResponseUsage`] — token accounting with nested details.
//!
//! Conventions (mirroring `crate::types`):
//!
//! * No `deny_unknown_fields`: unknown fields are forwarded verbatim through
//!   the per-struct `#[serde(flatten)] extra` map.
//! * Polymorphic unions are `#[serde(untagged)]` enums whose last variant is
//!   `Unknown(serde_json::Value)`, so an unmodelled payload round-trips
//!   losslessly instead of failing.
//! * Every union variant carries its own `type` discriminator
//!   (`#[serde(rename = "type")] kind`) plus its own `extra`.
//! * Deprecated fields (`truncation`, `user`, `prompt_cache_retention`,
//!   `reasoning.generate_summary`, `tools[].connector_id`) are deliberately
//!   not modelled; they fall into `extra` and are still forwarded.
//!
//! `Deserialize` for the type-tagged unions is generated by `type_tagged_union!`
//! rather than derived: because every variant keeps `kind: String` (the value
//! is never validated, per the gateway's "rejecting unknown values is an
//! anti-pattern" rule), a derived `untagged` impl would select the first
//! variant whose *shape* matches and let all-optional variants shadow later
//! ones. Dispatching on the raw `type` string keeps variant selection exact,
//! while unrecognised or malformed payloads still fall back to `Unknown`.

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};

/// Generate a `Deserialize` impl for a `type`-tagged union.
///
/// `$default_tag` is used when the payload omits `type` (pass `""` to disable).
/// A payload whose `type` matches a known tag but whose fields do not parse
/// falls through to `Unknown` — never an error, so nothing is lost.
macro_rules! type_tagged_union {
    ($target:ident, $default_tag:expr, { $($tag:literal => $variant:ident : $ty:ty),+ $(,)? }) => {
        impl<'de> serde::Deserialize<'de> for $target {
            fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
            where
                D: serde::Deserializer<'de>,
            {
                let value = serde_json::Value::deserialize(deserializer)?;
                let tag = value
                    .get("type")
                    .and_then(serde_json::Value::as_str)
                    .unwrap_or($default_tag);
                $(
                    if tag == $tag {
                        if let Ok(parsed) = serde_json::from_value::<$ty>(value.clone()) {
                            return Ok($target::$variant(parsed));
                        }
                    }
                )+
                Ok($target::Unknown(value))
            }
        }
    };
}

/// Kind assumed by an `EasyInputMessage` that omits its `type` discriminator.
fn default_message_kind() -> String {
    "message".to_string()
}

